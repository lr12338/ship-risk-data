CREATE TABLE IF NOT EXISTS dataanalysis.ship_behavior_maritime_scene_audit (
    audit_key VARCHAR(64) PRIMARY KEY,
    batch_no VARCHAR(128) NOT NULL,
    behavior_type VARCHAR(32) NOT NULL,
    mmsi VARCHAR(32) NOT NULL,
    target_mmsi VARCHAR(32),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    behavior_rule_version VARCHAR(64),
    scene_policy_version VARCHAR(64) NOT NULL,
    snapshot_version VARCHAR(128) NOT NULL,
    snapshot_fingerprint VARCHAR(64) NOT NULL,
    dominant_scene VARCHAR(64),
    scene_confidence VARCHAR(16),
    shadow_decision VARCHAR(32) NOT NULL,
    inland_point_ratio DOUBLE PRECISION,
    lake_point_ratio DOUBLE PRECISION,
    canal_point_ratio DOUBLE PRECISION,
    internal_water_point_ratio DOUBLE PRECISION,
    territorial_sea_point_ratio DOUBLE PRECISION,
    offshore_eez_point_ratio DOUBLE PRECISION,
    high_seas_point_ratio DOUBLE PRECISION,
    land_point_ratio DOUBLE PRECISION,
    unknown_point_ratio DOUBLE PRECISION,
    conflict_point_ratio DOUBLE PRECISION,
    coast_distance_min_nm DOUBLE PRECISION,
    coast_distance_p50_nm DOUBLE PRECISION,
    coast_distance_max_nm DOUBLE PRECISION,
    evidence_json TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
