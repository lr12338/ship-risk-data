CREATE TABLE IF NOT EXISTS `dataanalysis`.`ship_behavior_maritime_scene_audit` (
    audit_key VARCHAR(64) NOT NULL PRIMARY KEY,
    batch_no VARCHAR(128) NOT NULL,
    behavior_type VARCHAR(32) NOT NULL,
    mmsi VARCHAR(32) NOT NULL,
    target_mmsi VARCHAR(32),
    start_time DATETIME NOT NULL,
    end_time DATETIME NOT NULL,
    behavior_rule_version VARCHAR(64),
    scene_policy_version VARCHAR(64) NOT NULL,
    snapshot_version VARCHAR(128) NOT NULL,
    snapshot_fingerprint VARCHAR(64) NOT NULL,
    dominant_scene VARCHAR(64),
    scene_confidence VARCHAR(16),
    shadow_decision VARCHAR(32) NOT NULL,
    inland_point_ratio DOUBLE,
    lake_point_ratio DOUBLE,
    canal_point_ratio DOUBLE,
    internal_water_point_ratio DOUBLE,
    territorial_sea_point_ratio DOUBLE,
    offshore_eez_point_ratio DOUBLE,
    high_seas_point_ratio DOUBLE,
    land_point_ratio DOUBLE,
    unknown_point_ratio DOUBLE,
    conflict_point_ratio DOUBLE,
    scene_transition_count INTEGER,
    coast_distance_min_nm DOUBLE,
    coast_distance_p50_nm DOUBLE,
    coast_distance_max_nm DOUBLE,
    evidence_json LONGTEXT,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_maritime_scene_batch (batch_no),
    KEY idx_maritime_scene_decision (batch_no, shadow_decision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
