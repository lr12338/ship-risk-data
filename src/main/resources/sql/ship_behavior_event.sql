CREATE TABLE IF NOT EXISTS `dataanalysis`.`ship_behavior_event` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `behavior_type` VARCHAR(32) NOT NULL COMMENT 'LOITERING=船舶徘徊, ALONGSIDE=船舶搭靠',
  `mmsi` VARCHAR(20) NOT NULL COMMENT '主船MMSI',
  `target_mmsi` VARCHAR(20) DEFAULT NULL COMMENT '搭靠目标船MMSI；徘徊为空',
  `start_time` DATETIME NOT NULL COMMENT '行为开始时间',
  `end_time` DATETIME NOT NULL COMMENT '行为结束时间',
  `duration_minutes` BIGINT DEFAULT NULL COMMENT '持续分钟数',
  `start_lon` DOUBLE DEFAULT NULL COMMENT '开始经度',
  `start_lat` DOUBLE DEFAULT NULL COMMENT '开始纬度',
  `end_lon` DOUBLE DEFAULT NULL COMMENT '结束经度',
  `end_lat` DOUBLE DEFAULT NULL COMMENT '结束纬度',
  `min_distance_nm` DOUBLE DEFAULT NULL COMMENT '搭靠期间最小两船距离，单位海里',
  `max_distance_nm` DOUBLE DEFAULT NULL COMMENT '徘徊活动半径或搭靠期间最大两船距离，单位海里',
  `avg_distance_nm` DOUBLE DEFAULT NULL COMMENT '搭靠期间平均两船距离，单位海里',
  `distance_variance_nm2` DOUBLE DEFAULT NULL COMMENT '搭靠期间距离方差，平方海里',
  `course_difference_degree` DOUBLE DEFAULT NULL COMMENT '搭靠期间平均同向航向差，度',
  `speed_difference_knots` DOUBLE DEFAULT NULL COMMENT '搭靠期间平均速度差，节',
  `parallel_ratio` DOUBLE DEFAULT NULL COMMENT '同向并行匹配点比例',
  `near_port` TINYINT(1) DEFAULT NULL COMMENT '事件是否位于港口区域',
  `near_anchor` TINYINT(1) DEFAULT NULL COMMENT '事件是否位于锚地区域',
  `open_sea` TINYINT(1) DEFAULT NULL COMMENT '事件是否位于开放海域',
  `own_ship_type` VARCHAR(64) DEFAULT NULL COMMENT '主船类型',
  `target_ship_type` VARCHAR(64) DEFAULT NULL COMMENT '目标船类型',
  `avg_speed` DOUBLE DEFAULT NULL COMMENT '片段平均航速',
  `point_count` INT DEFAULT NULL COMMENT '参与识别的轨迹点数量',
  `rule_version` VARCHAR(64) DEFAULT NULL COMMENT '规则版本，便于后续规则调整后区分结果',
  `batch_no` VARCHAR(64) DEFAULT NULL COMMENT '计算批次',
  `event_sub_type` VARCHAR(32) DEFAULT NULL COMMENT '徘徊子类型',
  `severity_level` VARCHAR(8) DEFAULT NULL COMMENT 'L0-L4',
  `event_score` DOUBLE DEFAULT NULL COMMENT '单事件风险分，0-100',
  `confidence_level` VARCHAR(16) DEFAULT NULL COMMENT 'HIGH/MEDIUM/LOW',
  `exclusion_flag` VARCHAR(32) DEFAULT NULL COMMENT 'EXCLUDED_NORMAL/DOWNGRADED_NORMAL_LIKELY/VALID_RISK_EVENT',
  `exclusion_reason` VARCHAR(512) DEFAULT NULL COMMENT '正常场景排除原因',
  `ais_gap_count` INT DEFAULT NULL COMMENT 'AIS gap次数',
  `max_ais_gap_minutes` BIGINT DEFAULT NULL COMMENT '最大AIS gap分钟数',
  `track_coverage_ratio` DOUBLE DEFAULT NULL COMMENT '轨迹覆盖率',
  `turn_count_per_hour` DOUBLE DEFAULT NULL COMMENT '每小时转向次数',
  `cog_change_per_hour` DOUBLE DEFAULT NULL COMMENT '每小时累计航向变化',
  `tortuosity` DOUBLE DEFAULT NULL COMMENT '轨迹曲折系数',
  `center_lon` DOUBLE DEFAULT NULL COMMENT '事件中心经度',
  `center_lat` DOUBLE DEFAULT NULL COMMENT '事件中心纬度',
  `radius_nm` DOUBLE DEFAULT NULL COMMENT '事件活动半径，海里',
  `score_detail_json` TEXT DEFAULT NULL COMMENT '评分明细JSON',
  `event_source` VARCHAR(16) DEFAULT NULL COMMENT 'TARGET_LIST/REGION',
  `region_id` VARCHAR(128) DEFAULT NULL COMMENT '区域任务编码',
  `region_fingerprint` VARCHAR(64) DEFAULT NULL COMMENT '区域几何指纹',
  `event_key` VARCHAR(64) DEFAULT NULL COMMENT '批次内稳定事件键',
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_behavior_mmsi_time` (`behavior_type`, `mmsi`, `start_time`),
  KEY `idx_target_mmsi_time` (`target_mmsi`, `start_time`),
  KEY `idx_batch_no` (`batch_no`),
  KEY `idx_batch_region_behavior_time` (`batch_no`,`region_id`,`behavior_type`,`start_time`),
  UNIQUE KEY `uk_batch_event_key` (`batch_no`,`event_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='船舶行为事件候选结果（徘徊/搭靠）';
