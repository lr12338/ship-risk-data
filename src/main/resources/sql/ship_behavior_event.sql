CREATE TABLE IF NOT EXISTS `dataanalysis`.`ship_behavior_event` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `behavior_type` VARCHAR(32) NOT NULL COMMENT 'LOITERING=船舶徘徊, ALONGSIDE=船舶搭靠',
  `mmsi` VARCHAR(20) NOT NULL COMMENT '主船MMSI',
  `target_mmsi` VARCHAR(20) DEFAULT NULL COMMENT '搭靠目标船MMSI；徘徊为空',
  `start_time` DATETIME NOT NULL COMMENT '行为开始时间',
  `end_time` DATETIME NOT NULL COMMENT '行为结束时间',
  `duration_minutes` BIGINT DEFAULT NULL COMMENT '持续分钟数',
  `start_lon` DOUBLE DEFAULT NULL COMMENT '开始经度',
  `start_lat` DOUBLE DEFAULT NULL COMMENT '开始纬度',
  `end_lon` DOUBLE DEFAULT NULL COMMENT '结束经度',
  `end_lat` DOUBLE DEFAULT NULL COMMENT '结束纬度',
  `min_distance_nm` DOUBLE DEFAULT NULL COMMENT '搭靠期间最小两船距离，单位海里',
  `max_distance_nm` DOUBLE DEFAULT NULL COMMENT '徘徊活动半径或搭靠期间最大两船距离，单位海里',
  `avg_speed` DOUBLE DEFAULT NULL COMMENT '片段平均航速',
  `point_count` INT DEFAULT NULL COMMENT '参与识别的轨迹点数量',
  `rule_version` VARCHAR(32) DEFAULT NULL COMMENT '规则版本，便于后续规则调整后区分结果',
  `batch_no` VARCHAR(32) DEFAULT NULL COMMENT '计算批次',
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_behavior_mmsi_time` (`behavior_type`, `mmsi`, `start_time`),
  KEY `idx_target_mmsi_time` (`target_mmsi`, `start_time`),
  KEY `idx_batch_no` (`batch_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='船舶行为事件候选结果（徘徊/搭靠）';
