CREATE TABLE IF NOT EXISTS `dataanalysis`.`ship_behavior_loitering_batch_status` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `batch_no` VARCHAR(64) NOT NULL COMMENT '批量计算批次号',
  `mmsi` VARCHAR(20) NOT NULL COMMENT '船舶MMSI',
  `window_start_time` DATETIME NOT NULL COMMENT '切片开始时间',
  `window_end_time` DATETIME NOT NULL COMMENT '切片结束时间',
  `status` VARCHAR(20) NOT NULL DEFAULT 'DONE' COMMENT 'DONE=已完成, FAILED=失败',
  `point_count` INT DEFAULT NULL COMMENT '本切片轨迹点数量',
  `event_count` INT DEFAULT NULL COMMENT '兼容字段，本轮实际落库事件数量',
  `candidate_count` INT DEFAULT NULL COMMENT '过滤前候选事件数量',
  `weak_count` INT DEFAULT NULL COMMENT '弱候选数量',
  `downgraded_count` INT DEFAULT NULL COMMENT '正常场景降级候选数量',
  `valid_count` INT DEFAULT NULL COMMENT 'VALID_RISK_EVENT候选数量',
  `stored_event_count` INT DEFAULT NULL COMMENT '实际落库事件数量',
  `result_code` VARCHAR(20) DEFAULT NULL COMMENT 'SUCCESS/NO_DATA',
  `elapsed_ms` BIGINT DEFAULT NULL COMMENT '单船计算耗时毫秒',
  `error_message` VARCHAR(1024) DEFAULT NULL COMMENT '失败原因',
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_batch_mmsi_window` (`batch_no`, `mmsi`, `window_start_time`, `window_end_time`),
  KEY `idx_batch_status` (`batch_no`, `status`),
  KEY `idx_mmsi_time` (`mmsi`, `window_start_time`, `window_end_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='船舶徘徊批量计算进度表';
